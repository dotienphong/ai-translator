<li><strong>VietQR 주문:</strong> ‘받은 금액이 가격보다 적습니다. 24시간 이내에 주문 …의 나머지 금액을 송금하거나, 이 주문 번호와 함께 지원팀에 문의하세요.’ 차액을 송금하거나 지원팀에 문의하세요.</li>
