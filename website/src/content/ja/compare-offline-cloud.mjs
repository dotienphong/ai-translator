<p>統合については、全員が同じプラットフォームを使い、お使いのプランにすでにその機能が含まれているなら、会議プラットフォームに組み込まれた翻訳字幕のほうが便利です。追加でインストールするものも、ウィンドウを並べる手間もありません。AI Translator は独自の字幕バーを持つ別のアプリですが、その代わり、どの会議アプリ、ウェビナー、動画でも使えます。</p>

