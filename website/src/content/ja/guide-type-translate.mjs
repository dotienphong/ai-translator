<h2 id="language">どの言語に翻訳しますか？</h2>
<p>初期設定では、<strong>話している相手の言語</strong>に翻訳します。これは字幕の設定から決まります：「自動では、字幕の設定から相手の言語を使います。会議の言語が 1 つだけならその言語、それ以外は English（字幕が English の場合は Tiếng Việt）です。」たとえば、字幕を日本語で読み、音声の言語を英語に固定している場合、入力翻訳は英語に翻訳します。</p>
<p>いつも同じ言語を使うには、<strong>設定 › 入力翻訳</strong>を開き、<strong>翻訳先の言語</strong>で選びます：「自動（現在：…）」または 5 つの言語のどれかです。このグループには<strong>入力翻訳をオンにする</strong>スイッチもあり、オフにすると入力ボックスのショートカットは何もしません（選んだショートカットは保たれます）。</p>
